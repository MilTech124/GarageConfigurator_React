export function t(lang, key) {
  return translations[lang]?.[key] ?? translations.pl[key] ?? key;
}

export function translateOption(lang, value) {
  if (typeof value !== "string") {
    return value;
  }
  const fixed = directOptionFixes[value];
  if (fixed) {
    return lang === LANG.CS ? fixed.cs : fixed.pl;
  }
  const normalized = normalizeOption(value);
  const plValue = plLabels[normalized] ?? value;
  if (lang === LANG.CS) {
    return csLabels[normalized] ?? plValue;
  }
  return plValue;
}
